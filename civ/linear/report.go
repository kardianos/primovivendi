var partName = map[int]string{
	1: "reads forward",
	2: "subject and verb early",
	3: "one claim per sentence",
	4: "pronoun near its noun",
	5: "order of cause and effect",
}

var kinds = []string{"late verb", "long subject", "opening phrase", "second claim", "aside", "nested clauses", "long sentence", "distant pronoun", "bare this", "new before old", "effect before cause"}

type summary struct {
	n                            int
	words, pre, subj, mdd, depth []float64
	kind                         map[string]int
	scored                       int // sentences scoring 3 or more
	scoreSum                     float64
	lateVerb10, deep3            int
}

func summarize(ss []*sentence) summary {
	s := summary{kind: map[string]int{}}
	for _, x := range ss {
		s.n++
		s.words = append(s.words, float64(x.Words))
		s.pre = append(s.pre, float64(x.PreVerb))
		if x.SubjLen > 0 {
			s.subj = append(s.subj, float64(x.SubjLen))
		}
		s.mdd = append(s.mdd, x.MDD)
		s.depth = append(s.depth, float64(x.Depth))
		seen := map[string]bool{}
		for _, f := range x.Findings {
			if !seen[f.Kind] {
				s.kind[f.Kind]++
				seen[f.Kind] = true
			}
		}
		if x.Score >= 3 {
			s.scored++
		}
		if x.PreVerb > 10 {
			s.lateVerb10++
		}
		if x.Depth >= 3 {
			s.deep3++
		}
		s.scoreSum += x.Score
	}
	return s
}

func quantile(v []float64, q float64) float64 {
	if len(v) == 0 {
		return 0
	}
	c := append([]float64(nil), v...)
	sort.Float64s(c)
	i := int(q * float64(len(c)-1))
	return c[i]
}

func per100(k, n int) string {
	if n == 0 {
		return "0"
	}
	return fmt.Sprintf("%.1f", 100*float64(k)/float64(n))
}

func cmdReport(root, data, path string, perChapter int) error {
	srcs, err := loadSources(root, data)
	if err != nil {
		return err
	}
	var book, ref []*sentence
	byChapter := map[string][]*sentence{}
	var chapters []string
	for i := range srcs {
		s := &srcs[i]
		doc, text, err := loadParsed(data, *s)
		if err != nil {
			return err
		}
		ss := analyzeDoc(s, doc, text)
		if s.Ref {
			ref = append(ref, ss...)
			continue
		}
		book = append(book, ss...)
		byChapter[s.Name] = ss
		chapters = append(chapters, s.Name)
	}
	bs, rs := summarize(book), summarize(ref)

	var sb strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&sb, format+"\n", a...) }
	p("# 18. Rule 10 review: linear sentences")
	p("")
	p("Generated %s by `civ/linear` (`go run . parse`, then `go run . report`). Rerun after the chapters change; do not edit this file by hand.", time.Now().Format("2006-01-02"))
	p("")
	p("This is an editing aid for Rule 10 of the editing guide, not a verdict. A parser reads each sentence, and the tool scores it against the parts of the rule and drafts a rewrite where a mechanical one is safe. A parser misreads some sentences, and a draft rewrite can lose emphasis the sentence needs, so each flag is a reason to read the sentence again.")
	p("")
	p("## 1. What is measured")
	p("")
	p("| Part of Rule 10 | Measure | Weight | Draft rewrite |")
	p("|---|---|---|---|")
	p("| 1. Reads forward | The sentence opens on material absent from the sentence before and ends on words from it (\"new before old\"). | 1 | Names the words to open from. |")
	p("| 2. Subject and main verb early | Words before the main verb (over 10, 15, 22); a subject over 8 or 14 words; an opening phrase of 8 or more words before the subject (half weight when it states a condition, a time, or a cause, which part 5 keeps in front). | 1 to 3; 1 or 2; 0.5 or 1 | Pull back, for an opening of 10 or more words that does not point back to the previous sentence. |")
	p("| 3. One claim per sentence | A clause with its own subject, attached to the main clause, after a colon or semicolon; a parenthetical aside with a verb; clauses nested three or more deep (infinitives not counted); over 40 or 55 words. | 1; 1; 1 per level past two; 1 or 2 | Split at the colon or semicolon; move out an aside that is a sentence by itself. |")
	p("| 4. Pronoun near its noun | \"He,\" \"she,\" \"it,\" or \"they\" with no person, singular noun, or plural noun (or earlier pronoun of the same kind) in its sentence before it or in the sentence before; \"this,\" \"these,\" or \"those\" standing alone as a noun. Quotations, reflexives, and the \"it\" of \"it is clear that\" are skipped. | 2; 1 | Name it, when the parser links the pronoun to a noun of the right kind. |")
	p("| 5. Cause before effect | A \"because\" clause after the main clause. | 0.5 | Pull forward when the cause is 12 words or fewer. |")
	p("")
	p("The score of a sentence is the sum of its weights. The comparison sample is %d words of running prose from 8 works of 1859 to 1911, parsed the same way: %s.", int(sumF(rs.words)), refList())
	p("")

	p("## 2. The book against the period sample")
	p("")
	p("| Measure | Book | Period sample |")
	p("|---|---|---|")
	p("| Sentences | %d | %d |", bs.n, rs.n)
	p("| Sentence length, median and 90th percentile | %.0f, %.0f | %.0f, %.0f |", quantile(bs.words, .5), quantile(bs.words, .9), quantile(rs.words, .5), quantile(rs.words, .9))
	p("| Words before the main verb, median and 90th percentile | %.0f, %.0f | %.0f, %.0f |", quantile(bs.pre, .5), quantile(bs.pre, .9), quantile(rs.pre, .5), quantile(rs.pre, .9))
	p("| Sentences with more than 10 words before the main verb | %s%% | %s%% |", per100(bs.lateVerb10, bs.n), per100(rs.lateVerb10, rs.n))
	p("| Subject length, median and 90th percentile | %.0f, %.0f | %.0f, %.0f |", quantile(bs.subj, .5), quantile(bs.subj, .9), quantile(rs.subj, .5), quantile(rs.subj, .9))
	p("| Mean dependency distance, median and 90th percentile | %.2f, %.2f | %.2f, %.2f |", quantile(bs.mdd, .5), quantile(bs.mdd, .9), quantile(rs.mdd, .5), quantile(rs.mdd, .9))
	p("| Sentences with clauses nested three deep | %s%% | %s%% |", per100(bs.deep3, bs.n), per100(rs.deep3, rs.n))
	p("| Mean score | %.2f | %.2f |", bs.scoreSum/float64(max(bs.n, 1)), rs.scoreSum/float64(max(rs.n, 1)))
	p("| Sentences scoring 3 or more | %s%% | %s%% |", per100(bs.scored, bs.n), per100(rs.scored, rs.n))
	p("")
	p("Findings per 100 sentences:")
	p("")
	p("| Finding | Part | Book | Period sample |")
	p("|---|---|---|---|")
	kindPart := map[string]int{"late verb": 2, "long subject": 2, "opening phrase": 2, "second claim": 3, "aside": 3, "nested clauses": 3, "long sentence": 3, "distant pronoun": 4, "bare this": 4, "new before old": 1, "effect before cause": 5}
	for _, k := range kinds {
		p("| %s | %d | %s | %s |", k, kindPart[k], per100(bs.kind[k], bs.n), per100(rs.kind[k], rs.n))
	}
	p("")
	p("Mean dependency distance is the average number of words between a word and the word it attaches to; longer distances ask the reader to hold more in mind (H. Liu, \"Dependency Distance as a Metric of Language Comprehension Difficulty,\" *Journal of Cognitive Science* 9, 2008).")
	p("")

	p("## 3. By chapter")
	p("")
	p("| Chapter | Sentences | Mean score | Scoring 3+ | Words before verb, median | Late verb | Opening phrase | Second claim | Aside | Distant pronoun | Bare this | New before old | Effect before cause |")
	p("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
	for _, c := range chapters {
		s := summarize(byChapter[c])
		p("| %s | %d | %.2f | %s%% | %.0f | %d | %d | %d | %d | %d | %d | %d | %d |", c, s.n, s.scoreSum/float64(max(s.n, 1)), per100(s.scored, s.n), quantile(s.pre, .5),
			s.kind["late verb"], s.kind["opening phrase"], s.kind["second claim"], s.kind["aside"], s.kind["distant pronoun"], s.kind["bare this"], s.kind["new before old"], s.kind["effect before cause"])
	}
	p("")

	p("## 4. Sentences to read again")
	p("")
	p("Up to %d per chapter, highest score first, scoring 2.5 or more. The reference is the chapter and the Markdown line of the paragraph. Quotations inside the chapter's prose are parsed with it.", perChapter)
	p("")
	for _, c := range chapters {
		ss := append([]*sentence(nil), byChapter[c]...)
		sort.SliceStable(ss, func(i, j int) bool { return ss[i].Score > ss[j].Score })
		var pick []*sentence
		for _, s := range ss {
			if s.Score < 2.5 || len(pick) == perChapter {
				break
			}
			pick = append(pick, s)
		}
		if len(pick) == 0 {
			continue
		}
		sort.SliceStable(pick, func(i, j int) bool { return pick[i].Num < pick[j].Num })
		p("### %s (`%s`)", c, pick[0].Src.File)
		p("")
		for _, s := range pick {
			p("**%s:%d**, score %.1f", strings.TrimPrefix(c, "ch"), s.Line, s.Score)
			p("")
			p("> %s", s.Text)
			p("")
			for _, f := range s.Findings {
				p("- *Part %d, %s.* %s", f.Part, partName[f.Part], f.Note)
				if f.Suggest != "" {
					p("  - Draft (%s): %s", f.Move, f.Suggest)
				}
			}
			p("")
		}
	}

	p("## 5. Every draft rewrite, by kind of move")
	p("")
	p("Every sentence in the book for which the tool drafted a rewrite, whatever its score, in chapter order. Each entry gives the original and the draft.")
	p("")
	moves := []struct{ move, title, note string }{
		{"pull back", "Pull back", "A long opening phrase (a comparison, a setting, a source, or a concession) moves after the main clause, so that the sentence opens on its subject. Openings that state a condition, a time, or a cause are left in place."},
		{"pull forward", "Pull forward", "A short cause stated after its effect moves to the front."},
		{"split", "Split", "A colon or semicolon that joins two clauses becomes a full stop."},
		{"move out", "Move out", "A parenthetical aside becomes a sentence of its own after the sentence that held it."},
		{"name it", "Name it", "A pronoun with no noun of its kind nearby is replaced by the noun the parser links it to."},
	}
	for _, mv := range moves {
		var items []string
		for _, c := range chapters {
			for _, s := range byChapter[c] {
				for _, f := range s.Findings {
					if f.Move == mv.move && f.Suggest != "" {
						items = append(items, fmt.Sprintf("- **%s:%d.** %s\n  - Draft: %s", strings.TrimPrefix(c, "ch"), s.Line, s.Text, f.Suggest))
					}
				}
			}
		}
		p("### %s (%d)", mv.title, len(items))
		p("")
		p("%s", mv.note)
		p("")
		for _, it := range items {
			p("%s", it)
		}
		p("")
	}

	p("## 6. Method and limits")
	p("")
	p("- **Parser.** Stanford CoreNLP 4.6.0: tokens, parts of speech, lemmas, named entities, the shift-reduce constituency parser with Universal Dependencies converted from it, and neural coreference (C. Manning and others, \"The Stanford CoreNLP Natural Language Processing Toolkit,\" ACL 2014; K. Clark and C. Manning, \"Deep Reinforcement Learning for Mention-Ranking Coreference Models,\" EMNLP 2016). Attachment is right for most words of edited prose, and coreference is right for roughly four pronouns in five, so a flag about a pronoun deserves the most care.")
	p("- **Text.** Headings, block quotations, and tables are left out. Markup is removed. Inline quotations stay, because they are part of the sentence a reader meets.")
	p("- **\"New before old\"** compares the words before the main verb and the last five words with the content words (nouns, verbs, adjectives) of the previous sentence in the same paragraph. A pronoun, a connective, or a shared word at the start counts as a link. The first sentence of a paragraph is not checked.")
	p("- **Draft rewrites** are made by moving the parsed phrase and fixing the capital letter. They do not change wording, so a moved phrase can need a new connective, and a named pronoun can repeat a noun too often. A draft is offered only where the parse passes several checks: one main clause, the rest of the sentence starting with its subject, no pronoun left ahead of its noun, no quotation split, and no colon at the end. The other findings name the problem and leave the rewrite to the editor.")
	p("- **Parser errors.** The parser sometimes misreads a sentence, for example taking a whole clause for the subject (02:13). A finding that does not match the sentence is a parse error and can be ignored.")
	p("- **Not measured.** Whether a sentence ends on its new point, beyond the overlap test above, and whether the argument follows the order of events, beyond \"because.\"")

	if err := os.WriteFile(path, []byte(sb.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s\n", path)
	return nil
}

func sumF(v []float64) float64 {
	s := 0.0
	for _, x := range v {
		s += x
	}
	return s
}

func refList() string {
	var l []string
	for _, r := range refPicks {
		l = append(l, r.Label)
	}
	return strings.Join(l, "; ")
}
